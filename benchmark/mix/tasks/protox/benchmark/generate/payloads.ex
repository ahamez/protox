defmodule Mix.Tasks.Protox.Benchmark.Generate.Payloads do
  @moduledoc false

  use Mix.Task

  alias Benchmarks.BenchmarkDataset
  alias Benchmarks.Proto2.GoogleMessage1
  alias Opentelemetry.Proto.Trace.V1.TracesData
  alias Prometheus.WriteRequest
  alias ProtobufTestMessages.Proto3.TestAllTypesProto3
  alias Protox.Benchmark.{Ascii, Edge, Maps, RealisticValues}
  alias Protox.Benchmark.{Synthetic10, Synthetic100, Synthetic20, Synthetic200, Synthetic5, Synthetic50}
  alias Protox.RandomInit.EdgeCase
  alias StreamData

  require Logger

  @output "./benchmark/benchmark_payloads.bin"

  @nb_samples 10
  @max_payload_size 16_384 * 16

  # StreamData's size parameter, which drives repeated-field and map cardinality.
  #
  # The real-world schemas get their own values because depth, not size, is what makes them
  # big: once the generator reaches spans and samples, each extra element carries a whole
  # subtree. They also respond very differently to the same knob — at a shared value one is
  # starved of samples while the other runs to a megabyte — so they are tuned separately.
  @default_size 5
  @otel_size 10
  @prometheus_size 20

  # How deep the generator recurses. Generation stops dead at depth 0, so this bounds which
  # nested fields can be reached at all.
  #
  # The synthetic schemas and TestAllTypesProto3 are self-recursive (a message contains
  # itself), so a larger depth would explode; 2 is right for them.
  #
  # The real-world schemas are not recursive, and they nest deeply: reaching an OTel span
  # attribute means TracesData -> ResourceSpans -> ScopeSpans -> Span -> KeyValue, and
  # reaching a Prometheus sample means WriteRequest -> TimeSeries -> Sample. At depth 2 both
  # produced nothing but empty envelopes — hundreds of ResourceSpans with no scope_spans,
  # TimeSeries with no labels and no samples — so the inputs added to exercise deep nesting
  # and attribute lists exercised neither, and raising the size knob only multiplied the
  # empty shells.
  @default_depth 2
  @otel_depth 6
  @prometheus_depth 4

  # Inputs whose payloads are generated by walking the schema. Listed rather than
  # discovered because a module no longer maps to a single input: synthetic_100 feeds both
  # a realistic and an edge-case scenario, and the profile is what tells them apart.
  #
  # RealisticValues produces production-like values; EdgeCase is the property-testing
  # profile the test suite uses, kept for one input so the awkward cases stay measured.
  @generated [
    %{name: "synthetic_5", module: Synthetic5.Message, profile: RealisticValues, size: @default_size},
    %{name: "synthetic_10", module: Synthetic10.Message, profile: RealisticValues, size: @default_size},
    %{name: "synthetic_20", module: Synthetic20.Message, profile: RealisticValues, size: @default_size},
    %{name: "synthetic_50", module: Synthetic50.Message, profile: RealisticValues, size: @default_size},
    %{name: "synthetic_100", module: Synthetic100.Message, profile: RealisticValues, size: @default_size},
    %{name: "synthetic_200", module: Synthetic200.Message, profile: RealisticValues, size: @default_size},
    %{name: "maps", module: Maps.Message, profile: RealisticValues, size: @default_size},
    %{name: "test_all_types_proto3", module: TestAllTypesProto3, profile: RealisticValues, size: @default_size},
    %{
      name: "otel_traces_data",
      module: TracesData,
      profile: RealisticValues,
      size: @otel_size,
      depth: @otel_depth
    },
    %{
      name: "prometheus_write_request",
      module: WriteRequest,
      profile: RealisticValues,
      size: @prometheus_size,
      depth: @prometheus_depth
    },
    %{name: "synthetic_100_edge", module: Synthetic100.Message, profile: EdgeCase, size: @default_size}
  ]

  # Real captured payloads from Google's benchmark suite, as opposed to everything else
  # here, which is generated. See benchmark/protos/vendor/README.md.
  @datasets [
    {"google_message1_proto2", "./benchmark/protos/vendor/google/dataset.google_message1_proto2.pb", GoogleMessage1},
    {"google_message1_proto3", "./benchmark/protos/vendor/google/dataset.google_message1_proto3.pb",
     Benchmarks.Proto3.GoogleMessage1}
  ]

  @impl Mix.Task
  @spec run(any) :: any
  def run(_args) do
    # The whole corpus is built before the output is opened: loading a vendored dataset
    # can raise, and opening the file first would truncate the existing corpus before that
    # happened, leaving an empty artifact behind after a failed regeneration.
    payloads = Enum.reduce([generate_payloads(), build_ascii(), build_edge(), load_datasets()], &Map.merge/2)

    # Compressed because the decoded structs dominate the term: a Synthetic200 message
    # carries all 200 keys at every nesting level even when they hold defaults, so the
    # uncompressed corpus is ~100x the size of the encoded bytes it represents.
    File.write!(@output, :erlang.term_to_binary(payloads, compressed: 9))

    Logger.info("Wrote #{map_size(payloads)} inputs to #{@output}")
  end

  defp generate_payloads() do
    @generated
    |> Task.async_stream(&generate_payload/1, timeout: :infinity)
    |> Map.new(fn {:ok, entry} -> entry end)
  end

  defp generate_payload(%{name: name, module: mod, profile: profile, size: size} = input) do
    Logger.info("Generating payload for #{name}")

    samples =
      mod
      |> Protox.RandomInit.generate_fields_values(Map.get(input, :depth, @default_depth), profile)
      |> StreamData.bind(fn fields ->
        StreamData.constant(Protox.RandomInit.generate_struct(mod, fields))
      end)
      |> StreamData.resize(size)
      |> Stream.map(&measure(mod, &1))
      |> Stream.reject(fn {_msg, size, _bytes} -> size == 0 end)
      |> Stream.reject(fn {_msg, size, _bytes} -> size > @max_payload_size end)
      |> Enum.take(@nb_samples)

    {name, {mod, samples}}
  end

  # The datasets ship one real payload each, wrapped in a BenchmarkDataset message.
  #
  # `size` is protox's own encoded size rather than `byte_size(bytes)`, which are not
  # always equal here: the captured proto3 payload contains explicitly-written default
  # values that proto3 semantics omit on re-encode (228 bytes in, 221 bytes out). Keeping
  # the captured bytes as the decode input preserves the realism the dataset was added
  # for, while `size` stays the value the benchmark's pre-run encode check needs.
  defp load_datasets() do
    Map.new(@datasets, fn {name, path, mod} ->
      Logger.info("Loading dataset #{path} for #{name}")

      dataset =
        path
        |> File.read!()
        |> BenchmarkDataset.decode!()

      captured =
        Enum.map(dataset.payload, fn bytes ->
          msg = mod.decode!(bytes)
          {_msg, size, _reencoded} = measure(mod, msg)

          {msg, size, bytes}
        end)

      {name, {mod, batch(captured, path)}}
    end)
  end

  # Each dataset ships a single payload, but a Benchee iteration runs one codec call per
  # sample: a one-element input would do a tenth of the work of every other scenario, making
  # its ips, reductions and memory read on a different scale. Repeating to the common batch
  # size is also what the upstream harness does — its BenchmarkDataset docs say the payloads
  # are encoded or decoded in sequence, in a loop.
  defp batch([], path), do: Mix.raise("#{path} contains no payload")

  defp batch(captured, _path) do
    captured
    |> Stream.cycle()
    |> Enum.take(@nb_samples)
  end

  defp measure(mod, msg) do
    bytes =
      msg
      |> mod.encode!()
      |> elem(0)
      |> IO.iodata_to_binary()

    {msg, byte_size(bytes), bytes}
  end

  # -- Hand-built inputs
  #
  # These carry exact contents rather than a distribution, which is the point: the schema
  # cannot express "every string here is ASCII" or "every double here is NaN".

  @ascii_alphabet ~c"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,;:!?-_/"

  defp build_ascii() do
    samples = Enum.map(1..@nb_samples, fn n -> measure(Ascii.Message, ascii_message(n)) end)

    %{"ascii" => {Ascii.Message, samples}}
  end

  defp ascii_message(n) do
    struct!(Ascii.Message,
      field_1: ascii_text(16 * n),
      field_2: ascii_text(32 * n),
      field_3: ascii_text(64 * n),
      field_4: ascii_text(8 * n),
      field_5: ascii_text(128 * n),
      field_6: Enum.map(1..n, fn i -> ascii_text(24 * i) end),
      field_7: Enum.map(1..n, fn i -> ascii_text(48 * i) end),
      field_8: ascii_sub(n),
      field_9: Enum.map(1..n, &ascii_sub/1)
    )
  end

  defp ascii_sub(n) do
    struct!(Ascii.Sub,
      field_1: ascii_text(12 * n),
      field_2: ascii_text(20 * n),
      field_3: Enum.map(1..n, fn i -> ascii_text(16 * i) end)
    )
  end

  defp ascii_text(length) do
    @ascii_alphabet
    |> Stream.cycle()
    |> Enum.take(length)
    |> List.to_string()
  end

  @special_floats [:nan, :infinity, :"-infinity"]
  # Multi-byte UTF-8 so every string takes the slow path of the validator.
  @unicode_alphabet ~c"éàçüßöñ日本語한국어→★∑✓"

  defp build_edge() do
    Map.new(
      [
        {"edge_special_floats", :doubles, fn n -> Enum.map(1..(32 * n), &Enum.at(@special_floats, rem(&1, 3))) end},
        {"edge_unicode_strings", :strings, fn n -> Enum.map(1..(4 * n), fn i -> unicode_text(8 * i) end) end},
        {"edge_negative_varints", :ints, fn n -> Enum.map(1..(32 * n), &(-&1 * 7)) end}
      ],
      fn {name, field, fill} ->
        samples =
          Enum.map(1..@nb_samples, fn n ->
            measure(Edge.Message, struct!(Edge.Message, [{field, fill.(n)}]))
          end)

        {name, {Edge.Message, samples}}
      end
    )
  end

  defp unicode_text(length) do
    @unicode_alphabet
    |> Stream.cycle()
    |> Enum.take(length)
    |> List.to_string()
  end
end
